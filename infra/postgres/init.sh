#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$OPSATLAS_DB_PASSWORD" <<'SQL'
CREATE EXTENSION IF NOT EXISTS vector;
CREATE ROLE opsatlas LOGIN PASSWORD :'app_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
CREATE TABLE documents (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, model TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE chunks (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 document_id TEXT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
 page INTEGER NOT NULL CHECK(page>0), text TEXT NOT NULL,
 embedding vector(768) NOT NULL
);
CREATE INDEX chunks_document_id_idx ON chunks(document_id);
GRANT CONNECT ON DATABASE opsatlas TO opsatlas;
GRANT USAGE ON SCHEMA public TO opsatlas;
GRANT SELECT,INSERT,UPDATE,DELETE ON documents,chunks TO opsatlas;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO opsatlas;
SQL
